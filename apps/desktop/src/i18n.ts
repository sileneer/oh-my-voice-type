export type TFunc = (
  key: MessageKey,
  params?: Record<string, string | number>,
) => string;

/** Resolve the persisted setting ("auto" | "en" | "zh-CN") to a locale. */
export function resolveLocale(setting: string | null | undefined): Locale {
  if (setting === "zh-CN") return "zh-CN";
  if (setting === "en") return "en";
  const nav =
    typeof navigator !== "undefined" && navigator.language
      ? navigator.language
      : "en";
  return nav.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function makeT(locale: Locale): TFunc {
  return (key, params) => {
    let text: string = locale === "zh-CN" ? zhCN[key] : en[key];
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  };
}

